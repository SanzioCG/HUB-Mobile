// M-A6: `npm run icons` — assets/icons/*.svg, assets/illustrations/*.svg va brend logotiplaridan
// apps/mobile/src/ui/generated/*.tsx (react-native-svg `SvgXml` komponentlari) yasaydi. `currentColor` → `color` prop.
// `--check` — fayllar assets/ bilan mosligini tekshiradi (gate): eskirgan bo'lsa xato "npm run icons ni ishga tushiring".
// SVG almashtirilsa — shu buyruq; kod o'zgarmaydi (docs/design/ASSETS.md).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'apps/mobile/src/ui/generated');
const check = process.argv.includes('--check');

const pascal = (name) =>
  name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

/** Inter og'irligi → yuklangan shrift nomi (@expo-google-fonts/inter). */
const interFont = (weight) => {
  const w = Number(weight) || 400;
  if (w >= 650) return 'Inter_700Bold';
  if (w >= 550) return 'Inter_600SemiBold';
  if (w >= 450) return 'Inter_500Medium';
  return 'Inter_400Regular';
};

/** Metadata (C2PA), izohlar, ortiqcha nom maydonlari va bo'shliqlar olib tashlanadi; matn shrifti moslanadi. */
export function cleanSvg(svg) {
  let s = svg
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+xmlns:[a-z0-9]+="[^"]*"/gi, '')
    .replace(/>\s+</g, '><')
    .trim();
  // react-native-svg `font-family` ro'yxatini qo'llamaydi: "Inter,…" + og'irlik → yuklangan Inter fayli.
  s = s.replace(/<text\b([^>]*)>/g, (_m, attrs) => {
    const weight = /font-weight="([^"]*)"/.exec(attrs)?.[1];
    const a = attrs
      .replace(/\s*font-weight="[^"]*"/, '')
      .replace(/font-family="Inter[^"]*"/, `font-family="${interFont(weight)}"`);
    return `<text${a}>`;
  });
  return s;
}

const viewBoxOf = (svg) => {
  const m = /viewBox="([^"]+)"/.exec(svg);
  const [, , w, h] = (m?.[1] ?? '0 0 24 24').split(/[\s,]+/).map(Number);
  return { w, h };
};

const SOURCES = [
  { dir: 'assets/icons', kind: 'icon', suffix: 'Icon' },
  { dir: 'assets/illustrations', kind: 'illustration', suffix: 'Illustration' },
  {
    dir: 'assets/brand',
    kind: 'brand',
    suffix: '',
    only: ['logo-full.svg', 'logo-mark.svg', 'logo-master.svg'],
  },
];

function component(src, kind, comp, svg) {
  const { w, h } = viewBoxOf(svg);
  const ratio = +(w / h).toFixed(4);
  const usesColor = svg.includes('currentColor');
  return `// GENERATED by \`npm run icons\` from ${src} — qo'lda tahrir qilmang (SVG'ni almashtiring va buyruqni qayta ishga tushiring).
import { SvgXml } from 'react-native-svg';
import type { GeneratedSvgProps } from './types';

const XML = ${JSON.stringify(svg)};

/** ${kind}: viewBox ${w}×${h}${usesColor ? ', rang — `color` (currentColor)' : ''}. */
export function ${comp}({ size = ${kind === 'icon' ? 24 : 120}, color, style }: GeneratedSvgProps) {
  return <SvgXml xml={XML} width={size * ${ratio}} height={size} color={color} style={style} />;
}
`;
}

async function generate() {
  const files = new Map();
  const index = { icon: [], illustration: [], brand: [] };
  for (const s of SOURCES) {
    const dir = path.join(ROOT, s.dir);
    const names = readdirSync(dir)
      .filter((f) => f.endsWith('.svg') && (!s.only || s.only.includes(f)))
      .sort();
    for (const f of names) {
      const base = f.replace(/\.svg$/, '');
      const comp = `${pascal(base)}${s.suffix}`;
      const svg = cleanSvg(readFileSync(path.join(dir, f), 'utf8'));
      files.set(`${comp}.tsx`, component(`${s.dir}/${f}`, s.kind, comp, svg));
      index[s.kind].push({ base, comp });
    }
  }
  files.set(
    'types.ts',
    `// GENERATED by \`npm run icons\`.
import type { StyleProp, ViewStyle } from 'react-native';

export interface GeneratedSvgProps {
  /** Balandlik (px); eni viewBox nisbatida. */
  size?: number;
  /** \`currentColor\` o'rniga. */
  color?: string;
  style?: StyleProp<ViewStyle>;
}
`,
  );
  const entries = (list) => list.map(({ base, comp }) => `  '${base}': ${comp},`).join('\n');
  const imports = [...index.icon, ...index.illustration, ...index.brand]
    .map(({ comp }) => `import { ${comp} } from './${comp}';`)
    .join('\n');
  files.set(
    'index.ts',
    `// GENERATED by \`npm run icons\` — assets/ dan. Nomlar fayl nomi bilan bir xil.
${imports}

/** assets/icons — maxsus ikonkalar (24×24, currentColor). */
export const customIcons = {
${entries(index.icon)}
} as const;

/** assets/illustrations. */
export const illustrations = {
${entries(index.illustration)}
} as const;

export { ${index.brand.map((b) => b.comp).join(', ')} };
export type { GeneratedSvgProps } from './types';
`,
  );
  const options = (await prettier.resolveConfig(path.join(OUT, 'index.ts'))) ?? {};
  for (const [name, code] of files)
    files.set(name, await prettier.format(code, { ...options, filepath: path.join(OUT, name) }));
  return files;
}

const files = await generate();
if (check) {
  const stale = [];
  for (const [name, code] of files) {
    const p = path.join(OUT, name);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== code) stale.push(name);
  }
  const extra = existsSync(OUT) ? readdirSync(OUT).filter((f) => !files.has(f)) : [];
  if (stale.length || extra.length) {
    console.error(
      `Ikonkalar assets/ bilan mos emas (${[...stale, ...extra].join(', ')}): npm run icons ni ishga tushiring`,
    );
    process.exit(1);
  }
  console.log(`ikonkalar mos: ${files.size} fayl`);
} else {
  if (existsSync(OUT)) rmSync(OUT, { recursive: true });
  mkdirSync(OUT, { recursive: true });
  for (const [name, code] of files) writeFileSync(path.join(OUT, name), code);
  console.log(`${OUT}: ${files.size} fayl`);
}
